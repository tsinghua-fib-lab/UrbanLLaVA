import re

def extract_gpt_score(gpt_reply: str):
    gpt_reply = gpt_reply.strip()
    try:
        # Attempt to directly convert the reply to an integer
        score = int(gpt_reply)
    except:
        # Use regular expression to find the first number between 1 and 100
        match = re.search(r'\b(100|[1-9][0-9]?)\b', gpt_reply)
        if match:
            score = int(match.group(0))
        else:
            score = None  # Return None if no valid score is found
            raise ValueError(f"Cannot extract a score from the reply: {gpt_reply}")
    return score



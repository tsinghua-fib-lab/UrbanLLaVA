def get_judgeing_prompt(target:str, reference:str):

    rtn = f"""
    Here is a response generated by a LLM, you need to evaluate this response based on a given reference response.
    Reference response: {reference}
    Response: {target}
    Please only give me a score from 1 to 100, where 1 means the response is completely wrong, and 100 means the response is completely correct. If the response is partially correct, please give a score between 1 and 100.
    """

    return rtn.strip()

